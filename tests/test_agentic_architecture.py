    def _structured_decision(self, lyrics=None, *, scene_suffix="", character_label="guide"):
        lyrics = lyrics or ["Line one from model", "Line two from model"]
        scenes = []
        for index, line in enumerate(lyrics, start=1):
            scenes.append(
                {
                    "scene_num": index,
                    "lyric_line": line,
                    "narrative_function": "setup" if index == 1 else "payoff" if index == len(lyrics) else "development",
                    "relationship_to_previous": {
                        "kind": "opening" if index == 1 else "contrast",
                        "preserve": [] if index == 1 else ["same story world", f"same {character_label}"],
                        "change": [] if index == 1 else [f"visible lyric beat {index}", f"planned coverage {index}"],
                        "rationale": "establishes the story" if index == 1 else f"lyric {index} advances the causal arc",
                    },
                    "scene_goal": f"communicate lyric {index}{scene_suffix}",
                    "lyric_interpretation": f"planner interpretation for {line}{scene_suffix}",
                    "setting": f"a distinct full-frame storybook location {index} with foreground props and background depth{scene_suffix}",
                    "subjects": f"same rounded {character_label} with a soft scarf and friendly face",
                    "action": f"moves gently through beat {index} with clear child-safe expression{scene_suffix}",
                    "camera": f"Camera makes a slow planned move {index}",
                    "style": "soft pastel 3D animation, warm lighting, rounded uncluttered shapes",
                    "safety_adaptation": "no generated text, no dialogue, no inset frame, no scary imagery",
                    "selected_characters": [
                        {"label": character_label, "selection_rationale": f"fits lyric {index}"}
                    ],
                    "expected_mood": "calm bedtime mood",
                    "boundary_behavior": "fade" if index == len(lyrics) else "hold",
                    "cut": True,
                    "review_status": "pending",
                }
            )
        return {
            "lyrics": lyrics,
            "clip_count": len(lyrics),
            "target_duration_seconds": len(lyrics) * 5,
            "arc_summary": "The lead establishes a goal, develops it through successive lyric beats, and reaches a visible payoff.",
            "visual_bible": {
                "primary_world": "agent designed test world",
                "allowed_locations": [scene["setting"] for scene in scenes],
            },
            "selected_characters": [
                {
                    "label": character_label,
                    "description": f"same rounded {character_label} with a soft scarf and friendly face",
                    "selection_rationale": "chosen by planner fixture",
                    "continuity_constraints": ["same scarf"],
                    "negative_constraints": ["no text"],
                }
            ],
            "scenes": scenes,
            "music_prompt": "quiet celesta lullaby generated by backend",
        }

    def _plan(self):
        return build_production_plan(
            NurseryRhymeInput(
                rhyme_text="Twinkle, twinkle, little star,\nHow I wonder what you are!\nUp above the world so high,\n",
                target_duration_seconds=12,
                clip_count=3,
                seed=7,
            )
        )

    def test_planner_quantizes_segments_and_keeps_character_bank_out_of_prompts(self):
        plan = self._plan()
        self.assertEqual(plan.clip_count, 3)
        self.assertEqual(len(plan.character_bank), 3)
        for segment in plan.lyric_segments:
            self.assertAlmostEqual(segment.start_seconds * 24, round(segment.start_seconds * 24), places=5)
            self.assertAlmostEqual(segment.end_seconds * 24, round(segment.end_seconds * 24), places=5)
        self.assertLess(len(plan.scenes[0].video_prompt), 900)
        self.assertIn("toddler-safe lullaby animation", plan.scenes[0].video_prompt)
        self.assertIn("StoryMem keyframe memory", plan.scenes[0].video_prompt)
        self.assertIn("preserves identity/style across this shot", plan.scenes[0].video_prompt)
        self.assertIn("no picture-in-picture", plan.scenes[0].video_prompt)
        self.assertNotIn("pajama_child", plan.scenes[0].video_prompt)
        self.assertNotIn("smiling_star", plan.scenes[0].video_prompt)

